export function nextLine(kind) {
  if (kind === 'term') {
    const t = pick(TERM);
    return { t, c: t[0] === '✓' ? '#6dffa6' : t[0] === '$' ? '#ffffff' : t.startsWith('ERR') ? '#ff6b7a' : '#ffd866' };
  }
  if (kind === 'chat') {
    const t = pick(CHAT);
    return { t, c: t.startsWith('you') ? '#ffcb6b' : '#9fe3ff' };
  }
  const t = pick(CODE);
  return { t, c: t.includes('//') || t.includes('#') ? '#7f8aa8' : PAL[t.length % PAL.length] };
}

// beer goggles: scramble a few characters
export function typo(s, level) {
  if (!level) return s;
  const a = s.split('');
  for (let i = 0; i < a.length - 1; i++) {
    if (a[i] !== ' ' && Math.random() < level * 0.045) { const t = a[i]; a[i] = a[i + 1]; a[i + 1] = t; i++; }
  }
  return a.join('');
}
