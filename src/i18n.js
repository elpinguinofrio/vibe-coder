// sentences with a name / number inside
const PATTERNS = [
  [/^CLAUDE flagged (\S+): (.+)$/, (m) => `CLAUDE пометил ${m[1]}: ${tr(m[2])}`],
  [/^(.+) \(also: destroying evidence\)$/, (m) => `${tr(m[1])} (а ещё: уничтожение улик)`],
  [/^(\S+) BANNED$/, (m) => `${m[1]} ЗАБАНЕН`],
  [/^APPEALED {2}x(\d+)$/, (m) => `ОБЖАЛОВАНО  x${m[1]}`],
  [/^STREAK x(\d+): (.+) REINSTATED$/, (m) => `СЕРИЯ x${m[1]}: ${m[2]} ВОССТАНОВЛЕН`],
  [/^STREAK x(\d+): strike removed$/, (m) => `СЕРИЯ x${m[1]}: страйк снят`],
  [/^"(.+)"\?! -1\.5s$/, (m) => `«${t(m[1])}»?! −1,5 с`],
  [/^(.+) IS LIVE$/, (m) => `${t(m[1])} — В ПРОДЕ`],
  [/^"(.+)" is live\. Claude is furious\. Screenshot the receipt\.$/, (m) => `«${t(m[1])}» в проде. Claude в ярости. Сохраните чек.`],
];

export const LANGS = { en: 'English', ru: 'Русский' };
export const RU_KEYS = Object.keys(RU);
let lang = 'en';
try {
  const saved = localStorage.getItem('vcs-lang');
  lang = saved && LANGS[saved] ? saved : (navigator.language || 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en';
} catch (e) { /* storage blocked: stay with the default */ }
const listeners = [];

export const getLang = () => lang;
export function setLang(l) {
  if (!LANGS[l] || l === lang) return;
  lang = l;
  try { localStorage.setItem('vcs-lang', l); } catch (e) { /* not persisted */ }
  document.documentElement.lang = l;
  for (const f of listeners) f(l);
}
export const onLang = (f) => { listeners.push(f); };

// exact string
export function t(s) { return lang === 'ru' && Object.prototype.hasOwnProperty.call(RU, s) ? RU[s] : s; }
// exact string, or a sentence built from a template
export function tr(s) {
  if (lang !== 'ru' || typeof s !== 'string') return s;
  if (Object.prototype.hasOwnProperty.call(RU, s)) return RU[s];
  for (const [re, fn] of PATTERNS) { const m = s.match(re); if (m) return fn(m); }
  return s;
}
